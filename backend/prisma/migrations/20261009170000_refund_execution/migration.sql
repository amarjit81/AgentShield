CREATE TABLE "ApprovalRecord" (
  "id" UUID NOT NULL PRIMARY KEY,
  "requestId" UUID NOT NULL UNIQUE REFERENCES "ActionRequest"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "decision" TEXT NOT NULL,
  "snapshot" JSONB NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "ExecutionRecord" (
  "id" UUID NOT NULL PRIMARY KEY,
  "requestId" UUID NOT NULL UNIQUE REFERENCES "ActionRequest"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "result" JSONB NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "AuditEvent" (
  "id" SERIAL NOT NULL PRIMARY KEY,
  "requestId" UUID NOT NULL REFERENCES "ActionRequest"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "event" TEXT NOT NULL,
  "status" TEXT NOT NULL,
  "reason" TEXT NOT NULL,
  "details" JSONB NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "AuditEvent_requestId_id_idx" ON "AuditEvent"("requestId", "id");
